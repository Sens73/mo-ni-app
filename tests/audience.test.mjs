const content=JSON.parse(await readFile(new URL('data/content.json',root),'utf8'));
const archive=JSON.parse(await readFile(new URL('data/mathe-ag.json',root),'utf8'));
const archive56=JSON.parse(await readFile(new URL('data/mathe-ag-56.json',root),'utf8'));
const journey=JSON.parse(await readFile(new URL('data/journey.json',root),'utf8'));
assert.ok(archive.items.length>=120,'The primary-school archive only grows');
assert.equal(archive.items.filter(v=>matchesAudience(v,'34')).length,archive.items.length,'Every primary-school AG belongs to grades 3/4');
assert.equal(archive.items.filter(v=>matchesAudience(v,'56')).length,0);
assert.equal(archive56.items.filter(v=>matchesAudience(v,'34')).length,0);
assert.equal(archive56.items.filter(v=>matchesAudience(v,'56')).length,57);
assert.equal(archive56.items.filter(v=>v.enrichment).length,11);
assert.equal(archive56.nextNumber,58);
assert.equal(nextAgDate(content.dates,'56',now),null,'No invented grade-5 date');
