assert.equal(olympiadSeason({code:'NI660511'}),'66');
const now=new Date('2026-09-23T10:00:00Z');
const dates=[{type:'Mathe-AG',date:'2026-10-12',grades:[5,6]}, {type:'Mathe-AG',date:'2026-09-28',grades:[3,4]}, {type:'Mathe-AG',date:'2026-09-21',grades:[5,6]}, {type:'Mathe-AG',date:'2026-09-25',grades:[5,6],preview:true}];
